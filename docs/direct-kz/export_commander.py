def add_legacy_cols(ws):
    merged = [(r.min_row, r.min_col, r.max_row, r.max_col) for r in ws.merged_cells.ranges]
    for r in list(ws.merged_cells.ranges):
        ws.unmerge_cells(str(r))
    ws.insert_cols(9, SHIFT)
    for r1, c1, r2, c2 in merged:
        s = SHIFT if c1 >= 9 else 0
        ws.merge_cells(start_row=r1, start_column=c1 + s, end_row=r2, end_column=c2 + s)
    for i, name in enumerate(LEGACY):
        col = 9 + i
        ws.cell(10, col, name)._style = copy(ws.cell(10, 8)._style)
        ws.merge_cells(start_row=10, start_column=col, end_row=11, end_column=col)


def words(p):
    return {stem(w) for w in re.findall(r"[a-zа-яё0-9]+", p.lower()) if w not in STOP}


STOP = {"для", "в", "и", "по", "с", "на", "как", "через"}


def check(c):
    err = []
    for g in c["groups"]:
        heads, texts = ads(c, g)
        if len(heads) < 7:
            err.append(f"{g['name']}: заголовков {len(heads)} из 7")
        for h in heads:
            if len(h) > 56 or max(len(w) for w in h.split()) > 22:
                err.append(f"{g['name']}: заголовок «{h}» ({len(h)})")
        for t in texts:
            if len(t) > 81 or len(PUNCT.findall(t)) > 15 or max(len(w) for w in t.split()) > 23:
                err.append(f"{g['name']}: текст «{t}» ({len(t)})")
        if len(g["display"]) > 20:
            err.append(f"отображаемая ссылка «{g['display']}»")
    sl = c["sitelinks"]
    if len(sl) > 8 or any(sum(len(t) for t, _, _ in sl[i:i + 4]) > 66 for i in (0, 4)) \
            or any(len(t) > 30 or len(d) > 60 for t, d, _ in sl):
        err.append("быстрые ссылки длиннее лимита")
    if len(c["callouts"]) > 6 or any(len(x) > 25 for x in c["callouts"]):
        err.append("уточнения: больше 6 или длиннее 25")
    phrases = [p for g in c["groups"] for p in g["phrases"]]
    if len(phrases) != len(set(phrases)):
        err.append("фраза повторяется внутри кампании")
    for m in minus(c):
        for p in phrases:
            if stem(m.lstrip("-")) in words(p):
                err.append(f"минус «{m}» блокирует фразу «{p}»")
    return err


def overlaps():
    """Кампании одного места показа не должны ловить один и тот же запрос: если фраза Y целиком входит во фразу X
    другой кампании, кампания Y должна минусовать хотя бы одно слово из X."""
    err = []
    for cx in CAMPAIGNS:
        for cy in CAMPAIGNS:
            if cx is cy or cx["net"] != cy["net"]:
                continue
            my = {stem(m.lstrip("-")) for m in minus(cy)}
            for px in (p for g in cx["groups"] for p in g["phrases"]):
                for py in (p for g in cy["groups"] for p in g["phrases"]):
                    if words(py) <= words(px) and not my & words(px):
                        err.append(f"{cy['name']} «{py}» перехватит запрос «{px}» из {cx['name']}")
    return err


def stem(w):
    w = w.lower().replace("ё", "е")
    return w if len(w) <= 4 else (w[:len(w) - 2] if len(w) > 6 else w[:4])


def minus(c):
    return ["-" + m for m in sorted(set(MINUS_COMMON + c["minus"]))]


def ads(c, g):
    return list(dict.fromkeys(g["heads"] + c["heads"]))[:7], c["texts"][:3]


def fill(wb, c):
    ws = wb["Тексты"]
    if ws.max_row >= FIRST_ROW:
        ws.delete_rows(FIRST_ROW, ws.max_row - FIRST_ROW + 1)
    ws["E7"] = "Единая перфоманс-кампания"
    ws["E8"] = None
    ws["E9"] = " ".join(minus(c))
    ws["A6"] = f"Предложение текстовых блоков для кампании: {c['name']} ({c['net']})"
    sl_t = "||".join(t for t, _, _ in c["sitelinks"])
    sl_d = "||".join(d for _, d, _ in c["sitelinks"])
    sl_u = "||".join(utm(c["slug"], u, term=False) for _, _, u in c["sitelinks"])
    row, n = FIRST_ROW, 0
    for num, g in enumerate(c["groups"], 1):
        heads, texts = ads(c, g)
        link = utm(c["slug"], g.get("path", c["path"]))
        for p in g["phrases"]:
            n += 1
            ws.cell(row, C["plus"], "-")
            ws.cell(row, C["type"], "Комбинаторное")
            ws.cell(row, C["group"], g["name"])
            ws.cell(row, C["num"], num)
            ws.cell(row, C["phrase"], p)
            for i, h in enumerate(heads):
                ws.cell(row, C["h"] + i, h)
            for i, t in enumerate(texts):
                ws.cell(row, C["t"] + i, t)
            for i, col in enumerate(LEN_COLS):
                ref = f"{col}{row}"
                ws.cell(row, C["len"] + i, f'=IF({ref}="","",LEN(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE(SUBSTITUTE('
                        f'SUBSTITUTE(SUBSTITUTE({ref},"!",""),",",""),".",""),";",""),":",""),"""","")))')
            ws.cell(row, C["url"], link)
            ws.cell(row, C["display"], g["display"])
            ws.cell(row, C["region"], REGION)
            ws.cell(row, C["sl_t"], sl_t)
            ws.cell(row, C["sl_d"], sl_d)
            ws.cell(row, C["sl_u"], sl_u)
            ws.cell(row, C["callouts"], "||".join(c["callouts"]))
            row += 1
    return len(c["groups"]), n


